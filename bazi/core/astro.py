# ── ΔT（TT − UT）修正 ───────────────────────────────────────
def delta_t_seconds(year: float) -> float:
    """
    力学时与世界时之差（秒）。NASA/Espenak-Meeus 多项式分段拟合。
    VSOP87 级数以 TT 为自变量，而历法输入是 UT，必须补这个差值。
    """
    y = year
    if 1900 <= y < 1920:
        t = y - 1900
        return -2.79 + 1.494119 * t - 0.0598939 * t**2 + 0.0061966 * t**3 - 0.000197 * t**4
    if 1920 <= y < 1941:
        t = y - 1920
        return 21.20 + 0.84493 * t - 0.076100 * t**2 + 0.0020936 * t**3
    if 1941 <= y < 1961:
        t = y - 1950
        return 29.07 + 0.407 * t - t**2 / 233 + t**3 / 2547
    if 1961 <= y < 1986:
        t = y - 1975
        return 45.45 + 1.067 * t - t**2 / 260 - t**3 / 718
    if 1986 <= y < 2005:
        t = y - 2000
        return (63.86 + 0.3345 * t - 0.060374 * t**2 + 0.0017275 * t**3
                + 0.000651814 * t**4 + 0.00002373599 * t**5)
    if 2005 <= y < 2050:
        # Espenak-Meeus 多项式在 2016 年后高估（ΔT 实际增长放缓），
        # 故 2015-2025 用 IERS 实测值，之后按观测趋势平推。
        _OBS = {
            2015: 67.6, 2016: 68.1, 2017: 68.6, 2018: 69.0, 2019: 69.2,
            2020: 69.4, 2021: 69.4, 2022: 69.3, 2023: 69.2, 2024: 69.2,
            2025: 69.2,
        }
        if int(y) in _OBS:
            return _OBS[int(y)]
        if 2015 < y < 2025:
            lo = int(y)
            f = y - lo
            return _OBS[lo] + (_OBS.get(lo + 1, _OBS[2025]) - _OBS[lo]) * f
        if y <= 2015:
            t = y - 2000
            return 62.92 + 0.32217 * t + 0.005589 * t * t
        # 2025 之后：假设 ΔT 缓慢继续增长（每年 +0.1s，偏保守）
        return 69.2 + 0.1 * (y - 2025)
    if 2050 <= y < 2150:
        return -20 + 32 * ((y - 1820) / 100) ** 2 - 0.5628 * (2150 - y)
    u = (y - 1820) / 100
    return -20 + 32 * u * u


def jd_tt(jd_ut: float) -> float:
    """UT 儒略日 → TT 儒略日。"""
    year = 2000.0 + (jd_ut - 2451545.0) / 365.25
    return jd_ut + delta_t_seconds(year) / 86400.0


# ── 儒略日 ──────────────────────────────────────────────────
def julian_day(dt: datetime) -> float:
    """UTC datetime → 儒略日（含小数）。"""
    y, m = dt.year, dt.month
    d = dt.day + (dt.hour + dt.minute / 60 + dt.second / 3600) / 24
    if m <= 2:
        y -= 1
        m += 12
    a = y // 100
    b = 2 - a + a // 4
    return int(365.25 * (y + 4716)) + int(30.6001 * (m + 1)) + d + b - 1524.5


def jd_to_datetime(jd: float, keep_subsec: bool = False):
    """
    儒略日 → UTC datetime。

    keep_subsec=True 时把亚秒也保留进 microsecond，供节气精确换算用。
    """
    jd += 0.5
    z = int(jd)
    f = jd - z
    if z < 2299161:
        a = z
    else:
        alpha = int((z - 1867216.25) / 36524.25)
        a = z + 1 + alpha - alpha // 4
    b = a + 1524
    c = int((b - 122.1) / 365.25)
    d = int(365.25 * c)
    e = int((b - d) / 30.6001)
    day = b - d - int(30.6001 * e) + f
    month = e - 1 if e < 14 else e - 13
    year = c - 4716 if month > 2 else c - 4715
    di = int(day)
    frac = (day - di) * 24
    hh = int(frac)
    mm_f = (frac - hh) * 60
    mm = int(mm_f)
    sec_f = (mm_f - mm) * 60
    if keep_subsec:
        ss = int(sec_f)
        us = int(round((sec_f - ss) * 1e6))
        if us >= 1000000:
            us -= 1000000
            ss += 1
    else:
        ss = int(round(sec_f))
        us = 0
    if ss == 60:
        ss = 0
        mm += 1
    if mm == 60:
        mm = 0
        hh += 1
    return datetime(year, month, di, min(hh, 23), min(mm, 59), ss, us, tzinfo=timezone.utc)


