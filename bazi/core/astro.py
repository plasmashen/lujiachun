# 24 节气对应的太阳黄经（立春 = 315°）
SOLAR_TERM_NAMES = [
    "春分", "清明", "谷雨", "立夏", "小满", "芒种",
    "夏至", "小暑", "大暑", "立秋", "处暑", "白露",
    "秋分", "寒露", "霜降", "立冬", "小雪", "大雪",
    "冬至", "小寒", "大寒", "立春", "雨水", "惊蛰",
]
# 起点：春分 0°
TERM_LONGITUDE = {name: (i * 15) % 360 for i, name in enumerate(SOLAR_TERM_NAMES)}


def solar_term_time(year: int, name: str) -> datetime:
    """
    返回某年某节气的精确时刻（北京时间）。

    以「该节气在公历年内的大致日期」为初值，再用牛顿迭代把太阳视黄经
    收敛到目标值。这样每个节气都稳定落在 year 年内，不会跨到邻年。

    黄经 → 公历日期对照（春分 0° 起，每 15° 一节）：
      0°春分 3/20, 15°清明 4/5, ..., 270°冬至 12/22, 285°小寒 1/6, 300°大寒 1/20, 315°立春 2/4
    """
    target = TERM_LONGITUDE[name]
    idx = SOLAR_TERM_NAMES.index(name)

    # 春分(0°) 在年内第 79 天，每节 +15.2 天；黄经 > 270° 的（小寒/大寒/立春/雨水/惊蛰）
    # 属于「年初」，需回绕到 year 年 1-3 月
    approx_doy = 79 + idx * 15.2184
    if approx_doy > 365:
        approx_doy -= 365.2422
    jd = julian_day(datetime(year, 1, 1, tzinfo=timezone.utc)) + approx_doy

    for _ in range(40):
        lam = sun_apparent_longitude(jd_tt(jd))
        diff = (target - lam + 180) % 360 - 180
        if abs(diff) < 1e-8:
            break
        jd += diff * 365.2422 / 360.0

    return jd_to_datetime(jd, keep_subsec=True).astimezone(CST)


def solar_terms_of_year(year: int) -> dict[str, datetime]:
    return {n: solar_term_time(year, n) for n in SOLAR_TERM_NAMES}


