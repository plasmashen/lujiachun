  /** 洗牌 */
  function shuffle() {
    var d = DECK.map(function (c, i) { return { card: c, order: i }; });
    for (var i = d.length - 1; i > 0; i--) {
      var j = Math.floor(Math.random() * (i + 1));
      var t = d[i]; d[i] = d[j]; d[j] = t;
    }
    return d;
  }

